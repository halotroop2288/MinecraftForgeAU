package risugami.modloader.mixin;

import risugami.modloader.ModLoader;

import com.llamalad7.mixinextras.expression.Definition;
import com.llamalad7.mixinextras.expression.Expression;
import com.llamalad7.mixinextras.sugar.Local;
import net.minecraft.entity.mob.player.PlayerEntity;
import net.minecraft.inventory.slot.CraftingResultSlot;
import net.minecraft.item.ItemStack;
import org.jetbrains.annotations.NotNull;
import org.spongepowered.asm.mixin.Mixin;
import org.spongepowered.asm.mixin.Shadow;
import org.spongepowered.asm.mixin.injection.At;
import org.spongepowered.asm.mixin.injection.Inject;
import org.spongepowered.asm.mixin.injection.callback.CallbackInfo;

@Mixin(CraftingResultSlot.class)
public class CraftingResultSlotMixin {
	@Shadow
	private PlayerEntity player;

	@Definition(id = "i", local = @Local(type = int.class, ordinal = 0))
	@Expression("i = 0")
	@Inject(method = "onItemRemoved", at = @At("MIXINEXTRAS:EXPRESSION"))
	private void modloader$onItemRemoved_beforeForLoop(@NotNull ItemStack result, @NotNull CallbackInfo ci) {
		ModLoader.takenFromCrafting(this.player, result);
	}
}
